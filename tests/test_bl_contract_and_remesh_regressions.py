"""Regressions found while auditing every write_meshdict() caller for the
BL-contract / patch-typing bugs already fixed in watertight.py and the main
GUI's RetryRunner fallback.

Same bug, found duplicated in three more places:
- fault_tolerant.py and mesh_engine.py stored/emitted BL params using the
  pre-fix contract (thickness_ratio as a first-layer FRACTION plus a separate
  expansionRatio) and never passed patch_names — same silent-failure pattern
  as watertight.py: layers collapse (sub-1 "growth ratio" clamped to a
  default, no absolute first layer ever emitted) and inlet/outlet patches
  revert to cfMesh's default `wall` type.
- optimizer.py's fix loop had the identical BL-contract bug, AND a separate,
  more serious defect: it created a RetryRunner and never called .run() on
  it, so the loop rewrote meshDict with relaxed parameters but re-checked the
  SAME unchanged mesh every iteration — it could never actually improve
  anything.
"""
